CREATE TABLE TASK_AI_EMBEDDINGS (
    EMBEDDING_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,

    TASK_ID NUMBER NOT NULL,

    CONTENT_TEXT CLOB NOT NULL,

    EMBEDDING_MODEL VARCHAR2(100) DEFAULT 'gemini-embedding-2' NOT NULL,
    EMBEDDING_DIMENSIONS NUMBER DEFAULT 768 NOT NULL,

    EMBEDDING VECTOR(768, FLOAT32) NOT NULL,

    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_TASK_AI_EMBEDDINGS PRIMARY KEY (EMBEDDING_ID),

    CONSTRAINT UK_TASK_AI_EMBEDDINGS_TASK UNIQUE (TASK_ID),

    CONSTRAINT FK_TASK_AI_EMBEDDINGS_TASK
        FOREIGN KEY (TASK_ID)
        REFERENCES TASKS(TASK_ID)
);